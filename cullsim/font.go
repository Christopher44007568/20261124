// Text draws a string at (x, y) with integer pixel scaling.
func (c *Canvas) Text(x, y int, s string, col RGB, scale int) {
	cx := x
	for _, r := range s {
		g, ok := font5x7[r]
		if !ok {
			g = font5x7[' ']
		}
		for row := 0; row < 7; row++ {
			for colI := 0; colI < 5; colI++ {
				if g[row][colI] == '#' {
					for dy := 0; dy < scale; dy++ {
						for dx := 0; dx < scale; dx++ {
							c.Set(cx+colI*scale+dx, y+row*scale+dy, col)
						}
					}
				}
			}
		}
		cx += 6 * scale
	}
}

// TextWidth returns the pixel width of a string at the given scale.
func TextWidth(s string, scale int) int {
	return len(s) * 6 * scale
}
