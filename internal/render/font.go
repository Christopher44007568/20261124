const (
	glyphWidth  = 5
	glyphHeight = 7
	glyphGap    = 1
)

// textWidth returns the rendered width of text at the given pixel scale.
func textWidth(text string, scale int) int {
	runes := []rune(text)
	if len(runes) == 0 {
		return 0
	}
	return len(runes)*(glyphWidth*scale+glyphGap*scale) - glyphGap*scale
}

// drawText renders text starting at (x,y). Unknown runes render as spaces.
func drawText(pixels []byte, stride, x, y, scale int, text string, color byte) {
	for index, r := range []rune(text) {
		glyph, ok := glyph5x7[r]
		if !ok {
			glyph = glyph5x7[' ']
		}
		originX := x + index*(glyphWidth+glyphGap)*scale
		for row := 0; row < glyphHeight; row++ {
			for col := 0; col < glyphWidth; col++ {
				if glyph[row]&(1<<(glyphWidth-1-col)) == 0 {
					continue
				}
				fillPixelBlock(pixels, stride, originX+col*scale, y+row*scale, scale, color)
			}
		}
	}
}

func fillPixelBlock(pixels []byte, stride, x, y, scale int, color byte) {
	for dy := 0; dy < scale; dy++ {
		for dx := 0; dx < scale; dx++ {
			offset := (y+dy)*stride + (x + dx)
			pixels[offset] = color
		}
	}
}
